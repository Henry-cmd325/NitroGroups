using AutoMapper;
using Cortex.Mediator.Commands;
using NitroGroups.Core.Users.Application.Abstractions;
using NitroGroups.Core.Users.Application.Abstractions.Services;
using NitroGroups.Core.Users.Domain.Entities;
using NitroGroups.Shared.Contracts;
using NitroGroups.Shared.Contracts.Users.Requests;
using NitroGroups.Shared.Contracts.Users.Responses;
using NitroGroups.Shared.Domain.DomainEvents.Users.Enums;

namespace NitroGroups.Core.Users.Application.UseCases.Musicians.Create
{
    public record CreateMusicianCommand(
        UserInfoData UserInfo, 
        MusicianProfileData MusicianProfile, 
        int IdGroup) : ICommand<Result<MusicianDto>>;
    
    public class CreateMusicianCommandHandler(
        IUnitOfWorkUser unitOfWork, 
        IAuthenticationService authService, 
        IMapper mapper) : ICommandHandler<CreateMusicianCommand, Result<MusicianDto>>
    {
        private readonly IUnitOfWorkUser _unitOfWork = unitOfWork;
        private readonly IAuthenticationService _authService = authService;
        private readonly IMapper _mapper = mapper;

        public async Task<Result<MusicianDto>> Handle(CreateMusicianCommand command, CancellationToken cancellationToken)
        {
            // Check if a user with this Auth0 ID already exists (created by /auth/sync)
            var existingUsers = await _unitOfWork.Users.FindAsync(u => u.Auth0Id == command.UserInfo.Auth0Id);
            var existingUser = existingUsers.FirstOrDefault();

            Musician newMusician;
            if (existingUser != null)
            {
                // Reuse existing user — just create the musician profile
                existingUser.UpdateUserType((UserType)command.UserInfo.UserType);
                newMusician = new Musician
                {
                    UserId = existingUser.Id,
                    User = existingUser,
                    ShortBio = command.MusicianProfile.ShortBio,
                    YearsExperience = command.MusicianProfile.YearsExperience,
                    IsOpenToJoin = command.MusicianProfile.IsOpenToJoin
                };
                await _unitOfWork.Musicians.CreateAsync(newMusician);
            }
            else
            {
                // No existing user — create both user and musician via AutoMapper
                newMusician = _mapper.Map<Musician>(command);
                await _unitOfWork.Musicians.CreateAsync(newMusician);
            }

            // Persist to get the UserId generated by the database
            await _unitOfWork.CompleteAsync();

            if (command.IdGroup != 0)
            {
                var groupExists = await _unitOfWork.GroupIntegrationService.CheckIfGroupExists(command.IdGroup);
                if (!groupExists)
                    return "El grupo al que se queria unir ya no existe";

                newMusician.RaiseMusicianWithGroupCreatedEvent(command.IdGroup);
            }
            else if (command.MusicianProfile.CreateGroup)
            {
                var groupName = string.IsNullOrWhiteSpace(command.MusicianProfile.GroupName) 
                    ? $"{command.UserInfo.FirstName} {command.UserInfo.LastName}".Trim() 
                    : command.MusicianProfile.GroupName.Trim();
                newMusician.RaiseSoloMusicianCreatedEvent(groupName);
            }

            if (newMusician.DomainEvents.Count != 0)
            {
                await _unitOfWork.OutboxService.SaveEventsAsync(newMusician.DomainEvents);
                await _unitOfWork.CompleteAsync();
            }

            try 
            {
                await _authService.ActualizarTipoUsuario(newMusician.User.Auth0Id, UserType.BandMember);
            }
            catch (Exception)
            {
                // Ignorar en testing local si el Auth0Id no existe
            }
            return _mapper.Map<Musician, MusicianDto>(newMusician);
        }
    }
} 